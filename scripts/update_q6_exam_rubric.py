target_files = [
    ROOT / "ชุดข้อสอบใหม่" / "ชุดข้อสอบ_dataset.xlsx",
    ROOT / "ชุดข้อสอบใหม่" / "ชุดข้อสอบ_dataset_จัดรูปแบบใหม่.xlsx"
]

for fpath in target_files:
    if not fpath.exists():
        continue
    wb = openpyxl.load_workbook(fpath)
    if "Exam_Rubrics" in wb.sheetnames:
        ws = wb["Exam_Rubrics"]
        updated = False
        for row in range(5, ws.max_row + 1):
            q_val = ws.cell(row=row, column=1).value
            if str(q_val).strip() == "6":
                ws.cell(row=row, column=6, value=new_desc)
                updated = True
                print(f"Updated row {row} in {fpath.name}")
                break
        if updated:
            wb.save(fpath)
    wb.close()

print("Q6 Rubric update completed successfully.")
